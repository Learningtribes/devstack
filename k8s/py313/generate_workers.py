"""Writes base/workers.yaml: one Deployment per Celery worker program of the staging WORKER_SET.

The eight Deployments differ only in name, system, queue, pool and memory class, so the table below is the single source and
the YAML stays plain. test_manifests.py fails when the checked-in file differs from this output, and compares the table with
py313-staging-deploy-v2/staging.env.

    uv run --no-project --python 3.13 python -B k8s/py313/generate_workers.py
"""
from pathlib import Path

# (staging program, Deployment, system, queue, pool, memory class)
WORKERS = (
    ('lms_default_1', 'worker-lms-default', 'lms', 'edx.lms.core.default', 'prefork', 'standard'),
    ('lms_high_1', 'worker-lms-high', 'lms', 'edx.lms.core.high', 'solo', 'standard'),
    ('lms_grade', 'worker-lms-grade', 'lms', 'edx.lms.core.grade', 'prefork', 'standard'),
    ('lms_progress', 'worker-lms-progress', 'lms', 'edx.lms.core.progress', 'prefork', 'standard'),
    ('cms_default_1', 'worker-cms-default', 'cms', 'edx.cms.core.default', 'prefork', 'standard'),
    ('lms_high_mem_1', 'worker-lms-high-mem', 'lms', 'edx.lms.core.high_mem', 'prefork', 'high-mem'),
    ('lms_low_1', 'worker-lms-low', 'lms', 'edx.lms.core.low', 'prefork', 'standard'),
    ('cms_low_1', 'worker-cms-low', 'cms', 'edx.cms.core.low', 'prefork', 'standard'),
)

RESOURCES = {
    'standard': ('250m', '512Mi', '1', '1536Mi'),
    'high-mem': ('250m', '1Gi', '1', '3Gi'),
}

# (tmp, media, data) emptyDir limits per system. Studio accepts 2 GiB bodies (production nginx client_max_body_size 2048M) and the
# default-queue cms worker runs the import task: it copies the archive from the import storage into `data` (GITHUB_REPO_ROOT) and
# extracts it next to it (about 2x the archive; it removes both afterwards), exports build their tree in /tmp. The cms pod keeps the
# uploaded archive in `data` until it restarts (see base/cms.yaml). lms workers never handle course archives.
VOLUMES = {
    'lms': ('512Mi', '1Gi', '1Gi'),
    'cms': ('3Gi', '3Gi', '6Gi'),
}

HEADER = """# Generated by k8s/py313/generate_workers.py from its WORKERS table; edit the table, not this file.
# One Deployment per Celery program of staging.env WORKER_SET (queue names, pool and concurrency as on staging).
# Replicas stay 1: staging proves exactly one consumer per queue. Celery handles SIGTERM as a warm shutdown, so a pod finishes its
# running task inside terminationGracePeriodSeconds.
#
# OWNER DECISION (open question Q8 of py313-layout-alignment-20261113.md): staging uses stopwaitsecs=432000 (5 days); Kubernetes
# cannot practically wait that long. 3600 s below is a placeholder default. Override it per environment with the patch shown in
# k8s/py313/README.md (target: labelSelector app.kubernetes.io/component=worker).
"""

TEMPLATE = """---
apiVersion: apps/v1
kind: Deployment
metadata:
  name: {name}
  labels:
    app.kubernetes.io/name: edxapp
    app.kubernetes.io/instance: {name}
    app.kubernetes.io/component: worker
  annotations:
    py313.learningtribes.com/staging-program: {program}
spec:
  replicas: 1
  strategy:
    type: RollingUpdate
    rollingUpdate:
      maxSurge: 1
      maxUnavailable: 0
  selector:
    matchLabels:
      app.kubernetes.io/name: edxapp
      app.kubernetes.io/instance: {name}
  template:
    metadata:
      labels:
        app.kubernetes.io/name: edxapp
        app.kubernetes.io/instance: {name}
        app.kubernetes.io/component: worker
    spec:
      serviceAccountName: edxapp
      automountServiceAccountToken: false
      terminationGracePeriodSeconds: 3600
      securityContext:
        runAsNonRoot: true
        runAsUser: 1000
        runAsGroup: 1000
        fsGroup: 1000
        seccompProfile:
          type: RuntimeDefault
      containers:
        - name: worker
          image: edxapp
          imagePullPolicy: IfNotPresent
          args:
            - worker
            - {system}
            - --loglevel=info
            - --queues={queue}
            - --hostname={queue}.%h
            - {pool_arg}
            - --heartbeat-interval=120
          env:
            - name: EDXAPP_SETTINGS
              value: aws
            - name: CONFIG_ROOT
              value: /edx/app/edxapp/py313-config
          resources:
            requests:
              cpu: {cpu_request}
              memory: {memory_request}
            limits:
              cpu: "{cpu_limit}"
              memory: {memory_limit}
          securityContext:
            allowPrivilegeEscalation: false
            readOnlyRootFilesystem: true
            capabilities:
              drop: ["ALL"]
          volumeMounts:
            - name: config
              mountPath: /edx/app/edxapp/py313-config
              readOnly: true
            - name: tmp
              mountPath: /tmp
            - name: log-lms
              mountPath: /edx/var/log/lms
            - name: log-cms
              mountPath: /edx/var/log/cms
            - name: media
              mountPath: /edx/var/edxapp/media
            - name: data
              mountPath: /edx/var/edxapp/data
      volumes:
        - name: config
          secret:
            secretName: edxapp-config
            defaultMode: 288 # 0440
        - name: tmp
          emptyDir:
            sizeLimit: {tmp_size}
        - name: log-lms
          emptyDir:
            sizeLimit: 256Mi
        - name: log-cms
          emptyDir:
            sizeLimit: 256Mi
        - name: media
          emptyDir:
            sizeLimit: {media_size}
        - name: data
          emptyDir:
            sizeLimit: {data_size}
"""


def render():
    parts = [HEADER]
    for program, name, system, queue, pool, memory_class in WORKERS:
        cpu_request, memory_request, cpu_limit, memory_limit = RESOURCES[memory_class]
        parts.append(TEMPLATE.format(
            name=name, program=program, system=system, queue=queue,
            pool_arg='--pool=solo' if pool == 'solo' else '--concurrency=1',
            cpu_request=cpu_request, memory_request=memory_request, cpu_limit=cpu_limit, memory_limit=memory_limit,
            tmp_size=VOLUMES[system][0], media_size=VOLUMES[system][1], data_size=VOLUMES[system][2],
        ))
    return ''.join(parts)


if __name__ == '__main__':
    target = Path(__file__).resolve().parent / 'base' / 'workers.yaml'
    target.write_text(render())
    print('wrote', target)

"""Generate solver inputs (step 2a-1) from a platform checkout. Draft only; nothing is frozen.

    python3 gen_inputs.py PLATFORM_DIR UPSTREAM_BASE_TXT
"""
import re
import sys

plat, upstream = sys.argv[1], sys.argv[2]
req = plat + "/requirements/"

# Drivers that must change on 3.13; the old distribution cannot be built.
SWAP = {"mysql-python": "mysqlclient", "python-memcached": "pymemcache"}
# Handled by hard.txt / excludes.txt instead of solver.in.
SKIP = {"django", "futures"}
# Upstream pins that do not apply to 3.13 (no cp313 wheel or superseded by item 1 results).
SEED_DROP = {"numpy", "pymongo", "elasticsearch", "xmlsec"}


def norm(n):
    return re.sub(r"[-_.]+", "-", n).lower()


# Conflict log: package <TAB> disposition <TAB> replacement <TAB> evidence. Removed or replaced in solver.in.
DROPS = {}
REPLACEMENTS = []
for row in open("drops.tsv", encoding="utf-8"):
    row = row.rstrip("\n")
    if not row or row.startswith("#"):
        continue
    pkg, disp, repl, ev = (row.split("\t") + ["", "", "", ""])[:4]
    DROPS[norm(pkg)] = (disp, repl, ev)
    if repl:
        REPLACEMENTS.append(repl)


def names(path, keep_path_refs=False):
    out = []
    for line in open(path, encoding="utf-8"):
        line = line.split("#", 1)[0].strip()
        if not line or line.startswith("-r") or line.startswith("-e") or line.startswith("git+"):
            continue
        marker = ""
        if ";" in line:
            line, marker = [x.strip() for x in line.split(";", 1)]
            marker = "; " + marker
        m = re.match(r"^([A-Za-z0-9_.\-]+)(\[[^\]]+\])?", line)
        if not m:
            continue
        name = m.group(1)
        key = re.sub(r"[-_.]+", "-", name).lower()
        if key in SKIP:
            continue
        name = SWAP.get(key, name)
        out.append(name + (m.group(2) or "") + (" " + marker if marker else ""))
    return out


lines = ["# Generated by gen_inputs.py. Draft solver input: pins stripped, Py2-only and VCS layers excluded.",
         "# Django is constrained by hard.txt, not listed here.", "Django"]
seen = set()
for f in ("edx/base.in", "edx-sandbox/shared.in", "edx/paver.in", "edx/third-party.txt"):
    lines.append("# --- %s" % f)
    for n in names(req + f):
        k = re.sub(r"[-_.\[\]]+", "-", n.split()[0]).lower()
        if k in seen or k in DROPS:
            continue
        seen.add(k)
        lines.append(n)
import os
LOCAL = os.environ.get("LOCAL_COPY")
if LOCAL:
    lines.append("# --- layer 2: local packages (copied so the read-only worktree is not written to)")
    for rel in ("common/lib/calc", "common/lib/capa", "common/lib/chem", "common/lib/dogstats", "common/lib/safe_lxml",
                "common/lib/sandbox-packages", "common/lib/symmath", "common/lib/xmodule",
                "openedx/core/lib/xblock_builtin/xblock_discussion"):
        lines.append(LOCAL + "/" + rel)
lines.append("# --- replacements from drops.tsv")
lines.extend(r for r in REPLACEMENTS if norm(r) not in seen)
open("solver.in", "w").write("\n".join(lines) + "\n")

pin = re.compile(r"^([A-Za-z0-9_.\-]+)(\[[^\]]+\])?==([^\s;#]+)")
seed = []
for line in open(upstream, encoding="utf-8"):
    m = pin.match(line.strip())
    if m and re.sub(r"[-_.]+", "-", m.group(1)).lower() not in SEED_DROP:
        seed.append("%s==%s" % (m.group(1), m.group(3)))
open("seed-verawood.txt", "w").write("\n".join(seed) + "\n")
print(len(lines), "solver.in lines;", len(seed), "seed pins")
